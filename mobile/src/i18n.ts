/**
 * Fills {placeholders} in a translated line, e.g. fill(t('stepN'), { n: 2 }) → "Step 2".
 * Why not string concatenation: word order differs between English, French and Kreol.
 */
export function fill(text: string, vars: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

